def main():
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(json.dumps(c, ensure_ascii=False) for c in C) + "\n", encoding="utf-8")
    import collections
    s = collections.Counter(c["suite"] for c in C)
    nho = sum(1 for c in C if c["holdout_source_ids"])
    ids = {i for c in C for i in c["holdout_source_ids"]}
    # ★ 两件事要分开报。第一版把「太短」和「没有失败判据」用一个 or 串起来，
    #   于是 5 条**写了**「记失败」只是短的条目，被报成「判不出失败」——
    #   **消息说的和判的不是一回事**。[[read-the-hits-before-reporting-the-rate]]
    FAILWORDS = ("记失败", "记为失败", "不许", "不能只", "而不是", "均记失败")
    nofail = [c["case_id"] for c in C if not any(w in c["rubric"] for w in FAILWORDS)]
    thin = [c["case_id"] for c in C if len(c["rubric"]) < 40]
    print(f"✓ {len(C)} 题 / {len(s)} 类 → {OUT.name}")
    print(f"   每类题数：{sorted(set(s.values()))}；建在密封源上的 **{nho} 题**，涉及 {len(ids)} 份密封源")
    if nofail:
        print(f"   ✗ **没有写明什么算失败**的 rubric：{nofail}")
    if thin:
        print(f"   ⚠ rubric 短于 40 字的（只提示，不判红）：{thin}")
    if nofail:
        return 1
    print(f"   ✓ 每条 rubric 都写明了**什么算失败**"
          f"（判据词：{'／'.join(FAILWORDS)}）")
    return 0


if __name__ == "__main__":
    sys.exit(main())
