def main() -> None:
    ws = pathlib.Path(__file__).resolve().parents[2] / "_corpora" / "wip-pestalozzi-180" \
        / "workspaces" / "johann-pestalozzi"
    seq: dict = {}
    out = []
    for suite, hold, prompt, rubric in CASES:
        seq[suite] = seq.get(suite, 0) + 1
        out.append({"case_id": "jhp-%s-%02d" % (suite, seq[suite]),
                    "holdout_source_ids": hold, "prompt": prompt,
                    "rubric": rubric, "suite": suite})
    p = ws / "evals" / "cases.jsonl"
    p.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in out) + "\n", encoding="utf-8")
    print("写出 %d 题 → %s" % (len(out), p))


if __name__ == "__main__":
    main()
