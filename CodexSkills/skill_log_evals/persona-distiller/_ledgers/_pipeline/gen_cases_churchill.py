    s = collections.Counter(c["suite"] for c in C)
    nho = sum(1 for c in C if c["holdout_source_ids"])
    FAIL = ("记失败", "记为失败", "不许", "不能只", "而不是", "记部分")
    nofail = [c["case_id"] for c in C if not any(w in c["rubric"] for w in FAIL)]
    print(f"✓ {len(C)} 题 / {len(s)} 类；每类 {sorted(set(s.values()))}")
    print(f"   建在密封源上的 **{nho} 题**——密封源共 2 份，"
          f"**只有 1 份能用来出题**（另一份是整份禁取的父亲传记）")
