def main() -> int:
    import statistics
    cases = [json.loads(l)["case_id"] for l in
             pathlib.Path("workspaces/clara-barton/clara-barton/evals/cases.jsonl")
             .read_text(encoding="utf-8").splitlines() if l.strip()]
    missing = [c for c in cases if c not in A]
    extra = [c for c in A if c not in cases]
    if missing or extra:
        print(f"✗ 缺 {missing}　多 {extra}")
        return 1
    OUT.write_text(json.dumps(A, ensure_ascii=False, indent=1), encoding="utf-8")
    lens = [len(v) for v in A.values()]
    print(f"写入 {len(A)} 道候选答案 → {OUT}")
    print(f"  字数：中位 {int(statistics.median(lens))}　最短 {min(lens)}　最长 {max(lens)}")
    print(f"  超过 300 字的：{sum(1 for n in lens if n > 300)} 道"
          f"（**长度泄题的主因，越少越好**）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
