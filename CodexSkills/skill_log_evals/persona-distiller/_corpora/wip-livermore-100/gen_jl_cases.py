def main() -> int:
    target = pathlib.Path(sys.argv[1])
    led = [json.loads(l) for l in (target / "evidence/source-ledger.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    news_holdout = sorted(r["source_id"] for r in led
                          if r["split"] == "holdout" and "book" not in r.get("original_name", ""))
    assert news_holdout, "没有报纸 holdout"
    for c in CASES:
        if c.get("holdout_source_ids") == ["__NEWS_HOLDOUT__"]:
            c["holdout_source_ids"] = news_holdout[:1]

    cases_path = target / "evals/cases.jsonl"
    payload = []
    with cases_path.open("w", encoding="utf-8") as fh:
        for c in CASES:
            rec = {k: v for k, v in c.items() if not k.startswith("_")}
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
            fp = hashlib.sha256(json.dumps({
                "case_id": c["case_id"], "prompt": c["prompt"], "rubric": c["rubric"],
                "candidate": c["_candidate"], "baseline": c["_baseline"],
            }, ensure_ascii=False, sort_keys=True).encode()).hexdigest()[:16]
            payload.append({"case_id": c["case_id"], "suite": c["suite"],
                            "prompt": c["prompt"], "rubric": c["rubric"],
                            "candidate": c["_candidate"], "baseline": c["_baseline"],
                            "case_hash": fp})
    (target / "evals/judge_payload.v1.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8")

    import collections
    sc = collections.Counter(c["suite"] for c in CASES)
    print(f"写出 {len(CASES)} 条用例 → {cases_path}")
    print("套组分布:", dict(sorted(sc.items())))
    thin = [s for s, n in sc.items() if n < 2]
    print("不足 2 条的套组:", thin or "无")
    print("critical 条数:", sum(1 for c in CASES if c["critical"]))
    return 1 if thin else 0


if __name__ == "__main__":
    sys.exit(main())
