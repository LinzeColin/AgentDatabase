def main() -> int:
    ws = pathlib.Path(__file__).resolve().parent / "ws-galen/galen-of-pergamon"
    cases = [json.loads(l) for l in (ws / "evals/cases.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    ids = {c["case_id"] for c in cases}
    missing, extra = ids - set(A), set(A) - ids
    if missing or extra:
        print("缺:", sorted(missing), "多:", sorted(extra)); return 1
    out = pathlib.Path(__file__).resolve().parent / "galen_candidate.json"
    out.write_text(json.dumps(A, ensure_ascii=False, indent=1), encoding="utf-8")
    lens = [len(v) for v in A.values()]
    print(f"候选答案 {len(A)} 条；平均 {sum(lens)//len(lens)} 字符，最短 {min(lens)}，最长 {max(lens)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
