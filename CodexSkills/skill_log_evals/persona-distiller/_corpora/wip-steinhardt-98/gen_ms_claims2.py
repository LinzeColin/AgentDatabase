def main() -> int:
    fail = 0
    for c in CLAIMS:
        cmd = [sys.executable, LEDGER, "claim-add", str(T),
               "--claim", c["text"], "--category", c["cat"],
               "--status", c["status"], "--confidence", str(c["conf"])]
        for s in c["srcs"]:
            cmd += ["--source", s]
        for s in c["counter"]:
            cmd += ["--counter-source", s]
        for x in c["ctx"]:
            cmd += ["--context", x]
        for x in c["falsi"]:
            cmd += ["--falsifier", x]
        for x in c["alt"]:
            cmd += ["--alternative", x]
        if c["scope"]:
            cmd += ["--time-scope", c["scope"]]
        if c["appl"]:
            cmd += ["--applicability", c["appl"]]
        p = subprocess.run(cmd, capture_output=True, text=True)
        if p.returncode:
            fail += 1
            print(f"  ✗ {c['cid']}: {(p.stderr or p.stdout).strip()[:160]}")

    rows = [json.loads(l) for l in open(T / "evidence/claims.jsonl")]
    cat = Counter(r["category"] for r in rows)
    n_model = sum(1 for r in rows
                  if r["category"] == "mental-model" and r["status"] == "pattern")
    n_heur = sum(1 for r in rows
                 if r["category"] == "heuristic" and r["status"] == "pattern")
    print(f"\n写入 {len(rows)} 条，失败 {fail}")
    print("  category:", dict(sorted(cat.items())))
    print(f"  mental-model(pattern) = {n_model}   （deep 门 ≥4，本轮自加）")
    print(f"  heuristic(pattern)    = {n_heur}   （deep 门 ≥6，本轮自加）")
    assert n_model >= 4, (f"mental-model(pattern) {n_model} < 4"
                          f"  ← category 计数是 {cat['mental-model']}，**门不看这个**")
    assert n_heur >= 6, (f"heuristic(pattern) {n_heur} < 6"
                         f"  ← category 计数是 {cat['heuristic']}，**门不看这个**")
    for r in rows:
        if r["category"] == "soul-hypothesis":
            assert r["status"] == "hypothesis", f"{r['claim_id']} 必须是 hypothesis"
            assert r.get("alternative_explanations"), f"{r['claim_id']} 缺 alternative_explanations"
            assert r.get("falsifiers"), f"{r['claim_id']} 缺 falsifiers"
    print("  ✓ 下限与 soul-hypothesis 字段断言全过")
    return 0 if fail == 0 else 2


if __name__ == "__main__":
    sys.exit(main())
