def _documents() -> Mapping[Path, bytes]:
    source_documents = _source_material()
    index = build_evidence_index(source_documents)
    validate_evidence_index(index, source_documents)
    core = build_handoff_core(index)
    human_raw = _render_handoff(core, index)
    changelog_raw = _render_changelog(core, index)
    handoff = build_machine_handoff(
        index,
        _sha256(human_raw),
        _sha256(changelog_raw),
    )
    validate_machine_handoff(
        handoff,
        index,
        _sha256(human_raw),
        _sha256(changelog_raw),
    )
    index_schema = _constant_schema(
        EVIDENCE_INDEX_SCHEMA_ID,
        index,
        "index_digest",
        "Mechanism M-069 evidence index",
    )
    handoff_schema = _constant_schema(
        COLD_START_HANDOFF_SCHEMA_ID,
        handoff,
        "artifact_digest",
        "Mechanism M-069 cold-start Handoff",
    )
    contract = _extend_bundle(
        load_au040_acceptance().bundle,
        {
            EVIDENCE_INDEX_SCHEMA_ID: index_schema,
            COLD_START_HANDOFF_SCHEMA_ID: handoff_schema,
        },
        {
            EVIDENCE_INDEX_SCHEMA_ID: INDEX_SELF_POINTER,
            COLD_START_HANDOFF_SCHEMA_ID: SELF_POINTER,
        },
    )
    if len(contract.schemas) != 33 or len(contract.policies) != 5:
        raise ColdStartBuildError("M069_SCHEMA_OR_POLICY_COUNT_INVALID")
    validate_instance(
        contract,
        index,
        EVIDENCE_INDEX_SCHEMA_ID,
        expected_bundle_digest=CANDIDATE_BUNDLE_DIGEST,
        verify_digest=True,
        public=True,
    )
    validate_instance(
        contract,
        handoff,
        COLD_START_HANDOFF_SCHEMA_ID,
        expected_bundle_digest=CANDIDATE_BUNDLE_DIGEST,
        verify_digest=True,
        public=True,
    )
    scan_public_value(index, contract.policies)
    scan_public_value(handoff, contract.policies)
    return {
        EVIDENCE_INDEX_FILE: _render_json(index),
        MACHINE_HANDOFF_FILE: _render_json(handoff),
        HUMAN_HANDOFF_FILE: human_raw,
        CHANGELOG_FILE: changelog_raw,
        EVIDENCE_INDEX_SCHEMA_FILE: _render_json(index_schema),
        COLD_START_HANDOFF_SCHEMA_FILE: _render_json(handoff_schema),
    }


def _write() -> None:
    for path, raw in _documents().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(raw)


def _check() -> None:
    for path, expected in _documents().items():
        if not path.is_file() or path.is_symlink():
            raise ColdStartBuildError(
                "M069_GENERATED_FILE_INVALID:" + str(path)
            )
        if path.read_bytes() != expected:
            raise ColdStartBuildError(
                "M069_GENERATED_BYTE_DRIFT:" + str(path)
            )
    if VERSION_PATH.exists():
        raise ColdStartBuildError("M069_VERSION_MUST_REMAIN_ABSENT")


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        if args.write:
            _write()
        else:
            _check()
        index = _load(
            _documents()[EVIDENCE_INDEX_FILE],
            "M069_INDEX_INVALID",
        )
        print(
            "COLD_START_RELEASE_REVIEW_OK task="
            + FINAL_TASK_ID
            + " evidence="
            + str(len(index["entries"]))
            + " chat_required=false production_ready=false "
            "next=OWNER_SELECT_AND_RUN_FRESH_VERIFIER"
        )
        return 0
    except Exception as exc:
        print(str(exc), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
