class ColdStartBuildError(ValueError):
    """M-069 source, generated byte, schema, or trust closure failed."""


def _sha256(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def _render_json(value: Mapping[str, Any]) -> bytes:
    return (
        json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    ).encode("utf-8")


def _load(raw: bytes, code: str) -> Mapping[str, Any]:
    try:
        value = parse_json_bytes(raw)
    except Exception as exc:
        raise ColdStartBuildError(code) from exc
    if not isinstance(value, dict):
        raise ColdStartBuildError(code)
    return value


def _git_blob(tagged_object: str, relative_path: str) -> bytes:
    if (
        not tagged_object.startswith("sha1:")
        or len(tagged_object) != 45
    ):
        raise ColdStartBuildError("M069_GIT_OBJECT_INVALID")
    process = subprocess.run(
        [
            "git",
            "-C",
            str(REPO_ROOT),
            "show",
            tagged_object[5:] + ":" + relative_path,
        ],
        stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=20,
        check=False,
    )
    if process.returncode != 0:
        raise ColdStartBuildError(
            "M069_GIT_BLOB_UNAVAILABLE:" + relative_path
        )
    return process.stdout


def _is_ancestor(older: str) -> bool:
    process = subprocess.run(
        [
            "git",
            "-C",
            str(REPO_ROOT),
            "merge-base",
            "--is-ancestor",
            older[5:],
            "HEAD",
        ],
        stdin=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.PIPE,
        timeout=20,
        check=False,
    )
    return process.returncode == 0


def _current(relative_path: str) -> bytes:
    path = REPO_ROOT.joinpath(*relative_path.split("/"))
    if not path.is_file() or path.is_symlink():
        raise ColdStartBuildError(
            "M069_CURRENT_FILE_INVALID:" + relative_path
        )
    return path.read_bytes()


def _source_material():
    if not _is_ancestor(REVIEW_BASE_GIT_OBJECT_ID):
        raise ColdStartBuildError("M069_REVIEW_BASE_NOT_ANCESTOR")
    raw_documents = {}
    for spec in EVIDENCE_SPECS:
        source_raw = _git_blob(
            spec.source_git_object_id,
            spec.path,
        )
        review_raw = _git_blob(REVIEW_BASE_GIT_OBJECT_ID, spec.path)
        current_raw = _current(spec.path)
        if (
            source_raw != review_raw
            or review_raw != current_raw
            or _sha256(source_raw) != spec.content_digest
        ):
            raise ColdStartBuildError(
                "M069_SOURCE_BYTE_DRIFT:" + spec.code
            )
        _load(source_raw, "M069_SOURCE_JSON_INVALID:" + spec.code)
        raw_documents[spec.code] = source_raw
    return raw_documents


def _constant_schema(
    schema_id: str,
    value: Mapping[str, Any],
    digest_field: str,
    title: str,
) -> Mapping[str, Any]:
    properties = {
        key: {"const": item}
        for key, item in value.items()
        if key != digest_field
    }
    properties[digest_field] = {"$ref": COMMON_REF + "sha256"}
    return {
        "$id": schema_id,
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "additionalProperties": False,
        "properties": properties,
        "required": list(value),
        "title": title,
        "type": "object",
    }


def _extend_bundle(
    base: ContractBundle,
    additions: Mapping[str, Mapping[str, Any]],
    pointers: Mapping[str, str],
) -> ContractBundle:
    schemas = dict(base.schemas)
    self_pointers = dict(base.self_digest_pointers)
    for schema_id, schema in additions.items():
        if schema_id in schemas:
            raise ColdStartBuildError(
                "M069_SCHEMA_REBIND_FORBIDDEN:" + schema_id
            )
        schemas[schema_id] = schema
        self_pointers[schema_id] = pointers[schema_id]
    try:
        registry, checker = build_registry(schemas)
    except ContractError as exc:
        raise ColdStartBuildError(
            "M069_SCHEMA_CLOSURE_INVALID:" + str(exc)
        ) from exc
    return ContractBundle(
        schemas=schemas,
        registry=registry,
        format_checker=checker,
        self_digest_pointers=self_pointers,
        policies=base.policies,
        protocol_revision=base.protocol_revision,
    )


